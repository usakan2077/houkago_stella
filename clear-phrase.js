function vnCreateClearPhrase(bytes) {
  const words = VN_CLEAR_PHRASE_WORDS;
  // All four banks have 32 entries: byte modulo 32 is unbiased.
  return [words.first[bytes[0] % 32],
    words.subject[bytes[1] % 32] + 'が' + words.verb[bytes[2] % 32],
    words.last[bytes[3] % 32]].join('／');
}
