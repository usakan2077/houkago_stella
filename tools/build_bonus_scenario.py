from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
lines, texts = [], {'ja': {}, 'en': {}}


def command(value): lines.append(value)
def label(value): lines.extend(['', '# bonus_' + value])
def line(speaker, ja, en):
    key = f'r{len(texts["ja"])+1:03}'
    texts['ja'][key], texts['en'][key] = ja, en
    lines.append((speaker + ': ' if speaker else '> ') + '$bonus.' + key)
def choice(options):
    command('@choice')
    for ja, en, target in options:
        key = f'r{len(texts["ja"])+1:03}'
        texts['ja'][key], texts['en'][key] = ja, en
        command(f'- $bonus.{key} -> bonus_{target}')
def jump(target): command('@jump bonus_' + target)
def show(char, pos, expr='normal', effect='pop_in'): command(f'@show {char} {pos} {expr} {effect}')
def emote(char, motion, strength=1.5): command(f'@emote {char} {motion} {strength}')
def cg(key, reaction=None):
    command('@hide_all instant')
    command('@still bonus_' + key + ' slide_in_bottom')
    if reaction: command('@bonus impact ' + reaction)
def hide_cg(): command('@still_hide instant')


