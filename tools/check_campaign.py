"""Campaign placement, modal rules and keyboard behavior on the game and both LPs."""
def run(c, passed, out, base):
    # Keep campaign checks stable even when the host clock predates the announcement.
    c.send('Page.addScriptToEvaluateOnNewDocument',dict(source="Date.now=()=>Date.parse('2026-11-03T00:00:00+09:00')"))
    c.evaluate("Date.now=()=>Date.parse('2026-11-03T00:00:00+09:00');document.documentElement.lang='ja'")
    c.wait("document.querySelector('[data-campaign-status]').textContent.startsWith('キャンペーン開催中')")
    c.wait("getComputedStyle(document.getElementById('title-logo-wrapper')).opacity==='1'")
    assert c.evaluate("(()=>{const b=document.querySelector('[data-campaign-open]').getBoundingClientRect(),m=document.getElementById('btn-title-settings').getBoundingClientRect();return b.top>m.bottom+5&&b.bottom<innerHeight})()")
    assert c.evaluate("(()=>{const b=document.querySelector('[data-campaign-open]').getBoundingClientRect(),v=document.getElementById('title-version').getBoundingClientRect();return b.height===v.height&&b.top===v.top&&getComputedStyle(document.querySelector('[data-campaign-open] img')).display==='none'})()")
    c.shot('campaign-game-banner')
    passed('Game banner sits below the main menu without covering its controls')

    def check_modal(name):
        c.click('[data-campaign-open]')
        c.wait("document.querySelector('#stella-campaign-dialog[open] .campaign-poster')?.naturalWidth>1000")
        assert c.evaluate("document.querySelector('#stella-campaign-dialog ol').children.length===4")
        assert c.evaluate("document.querySelector('.campaign-deadline').textContent.includes('23:59')&&document.querySelector('.campaign-deadline').textContent.includes('2026')")
        assert c.evaluate("document.querySelector('#stella-campaign-dialog').textContent.includes('@houkago_stella')")
        assert c.evaluate("getComputedStyle(document.querySelector('.campaign-close')).cursor==='pointer'&&getComputedStyle(document.getElementById('stella-campaign-dialog')).cursor!=='none'&&getComputedStyle(document.querySelector('.campaign-poster')).cursor!=='none'")
        if c.evaluate("!!document.getElementById('custom-cursor')"):
            assert c.evaluate("getComputedStyle(document.getElementById('custom-cursor')).visibility==='hidden'")
        assert c.evaluate("(()=>{const d=document.getElementById('stella-campaign-dialog').getBoundingClientRect();return d.left>=0&&d.right<=innerWidth+1&&d.top>=0&&d.bottom<=innerHeight+1})()")
        c.shot(name)
        c.key('Escape')
        c.wait("!document.getElementById('stella-campaign-dialog').open&&document.activeElement.matches('[data-campaign-open]')")
        if c.evaluate("!!document.getElementById('custom-cursor')"):
            assert c.evaluate("getComputedStyle(document.getElementById('custom-cursor')).visibility!=='hidden'")

    check_modal('campaign-game-dialog')
    assert c.evaluate("document.querySelector('[data-campaign-status]').textContent==='キャンペーン開催中 · 日本国内在住者限定'")
    c.click('[data-campaign-open]')
    assert c.evaluate("document.querySelector('.campaign-dialog-actions a:last-child').href==='https://x.com/houkago_stella/status/2117251255106261117'&&document.querySelector('.campaign-notice').textContent.includes('2026')")
    c.key('Escape')
    assert c.evaluate("document.querySelector('.campaign-eligibility').textContent.includes('日本国内在住')")
    passed('Live campaign shows the announcement link, four entry steps and JST dates; Escape restores focus')

    c.evaluate("document.documentElement.lang='en'")
    c.wait("document.querySelector('[data-campaign-more]').textContent==='View rules'")
    check_modal('campaign-game-dialog-en')
    assert c.evaluate("document.querySelector('#stella-campaign-dialog h2').textContent==='Extra completion campaign'")
    assert c.evaluate("document.querySelector('.campaign-eligibility').textContent.includes('residents of Japan')&&document.querySelector('[data-campaign-status]').textContent.includes('Japan residents only')")
    passed('Game campaign copy and rules switch to English')

    c.evaluate("window._campaignOriginal={...STELLA_CAMPAIGN};STELLA_CAMPAIGN.startsAt=null;STELLA_CAMPAIGN.announcementUrl=null;document.documentElement.lang='ja'")
    c.wait("document.querySelector('[data-campaign-status]').textContent.startsWith('開催準備中')")
    c.click('[data-campaign-open]')
    assert c.evaluate("document.querySelectorAll('.campaign-dialog-actions a').length===1")
    c.key('Escape')
    c.evaluate("STELLA_CAMPAIGN.endsAt='2000-01-01T00:00:00Z';document.documentElement.lang='ja'")
    c.wait("document.querySelector('[data-campaign-status]').textContent.startsWith('応募受付終了')")
    c.click('[data-campaign-open]')
    assert c.evaluate("document.querySelector('#stella-campaign-dialog .campaign-status').textContent==='応募受付終了'")
    c.key('Escape')
    c.wait("!document.getElementById('stella-campaign-dialog').open")
    c.evaluate("STELLA_CAMPAIGN.startsAt='2999-01-01T00:00:00Z';STELLA_CAMPAIGN.endsAt='3000-01-01T00:00:00Z';STELLA_CAMPAIGN.announcementUrl='https://x.com/houkago_stella/status/1';document.documentElement.lang='en'")
    c.wait("document.querySelector('[data-campaign-status]').textContent.startsWith('Starts soon')")
    c.evaluate("Object.assign(STELLA_CAMPAIGN,_campaignOriginal)")
    passed('Deadline closes entries even without a launch date; a future launch shows scheduled status')

    for path,name in [('/lp/index.html','lp'),('/lp/ai/index.html','lp-ai')]:
        c.send('Page.navigate',dict(url=base+path))
        c.wait("!!document.querySelector('[data-campaign-open]')&&typeof STELLA_CAMPAIGN!=='undefined'")
        c.evaluate("document.documentElement.lang='ja'")
        c.wait("document.querySelector('[data-campaign-more]').textContent==='応募ルールを見る'")
        c.wait("document.querySelector('.campaign-lp img').naturalWidth>1000")
        c.evaluate("document.querySelector('[data-campaign-open]').scrollIntoView({block:'center',behavior:'instant'})")
        assert c.evaluate("(()=>{const i=document.querySelector('.campaign-lp img'),r=i.getBoundingClientRect();return r.width>350&&Math.abs(r.width/r.height-i.naturalWidth/i.naturalHeight)<.01&&getComputedStyle(i).objectFit==='contain'})()")
        c.shot('campaign-'+name+'-desktop-banner')
        check_modal('campaign-'+name+'-dialog')
        c.send('Emulation.setDeviceMetricsOverride',dict(width=390,height=844,deviceScaleFactor=1,mobile=True))
        check_modal('campaign-'+name+'-mobile-dialog')
        assert c.evaluate('document.documentElement.scrollWidth<=innerWidth+1')
        c.evaluate("document.querySelector('[data-campaign-open]').scrollIntoView({block:'center',behavior:'instant'})")
        assert c.evaluate("(()=>{const i=document.querySelector('.campaign-lp img'),r=i.getBoundingClientRect();return r.width>300&&Math.abs(r.width/r.height-i.naturalWidth/i.naturalHeight)<.01})()")
        c.shot('campaign-'+name+'-mobile-banner')
        c.click('[data-campaign-open]')
        c.click('#stella-campaign-dialog .campaign-close')
        c.wait("!document.getElementById('stella-campaign-dialog').open&&document.body.style.overflow!=='hidden'")
        passed(name+': desktop/mobile image and rules fit, close button works, background scrolling resumes')
        c.send('Emulation.setDeviceMetricsOverride',dict(width=1280,height=720,deviceScaleFactor=1,mobile=False))
    assert not c.errors,c.errors
    passed('No browser JavaScript exceptions on game or either LP')
