"""Compile Korean UI and native SVG text offline; no translation or generation API."""
import hashlib,html,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DRAFTS=ROOT/'locales/korean-drafts'
source_path=DRAFTS/'ui-source.json'
if source_path.exists():source=json.loads(source_path.read_text(encoding='utf-8'))
else:
    source=list(json.loads((ROOT/'locales/ui.zh-CN.json').read_text(encoding='utf-8')))
    source_path.write_text(json.dumps(source,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
entries={}
for line in (DRAFTS/'ui.txt').read_text(encoding='utf-8').splitlines():
    number,text=line.split('|',1);number=int(number)
    assert number not in entries and text.strip(),number
    entries[number]=text.replace('⏎','\n')
assert set(entries)==set(range(len(source))),(len(entries),len(source))
dictionary={}
for i,original in enumerate(source):
    value=entries[i]
    assert sorted(re.findall(r'\{\w+\}',original))==sorted(re.findall(r'\{\w+\}',value)),original
    assert re.findall(r'</?\w+[^>]*>',original)==re.findall(r'</?\w+[^>]*>',value),original
    dictionary[original]=value
extra=DRAFTS/'ui-extra.json'
if extra.exists():dictionary.update(json.loads(extra.read_text(encoding='utf-8')))
(ROOT/'locales/ui.ko.json').write_text(json.dumps(dictionary,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(ROOT/'korean-locales.js').write_text('/* Locally authored Korean interface; generated by tools/build_korean_ui.py. */\nglobalThis.StellaI18n.dictionaries.ko = '+json.dumps(dictionary,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
for svg in (ROOT/'assets/bonus').glob('*_ja*.svg'):
    def replace(match):
        original=html.unescape(match[2]);value=dictionary.get(original,original)
        return match[1]+html.escape(value,quote=False)+match[3]
    body=re.sub(r'(<(?:text|tspan)\b[^>]*>)([^<]+)(</(?:text|tspan)>)',replace,svg.read_text(encoding='utf-8'))
    body=body.replace('"Yu Gothic",','"Malgun Gothic", "Apple SD Gothic Neo",').replace('font-family="','font-family="Malgun Gothic, ')
    svg.with_name(svg.name.replace('_ja','_ko')).write_text(body,encoding='utf-8')
print('ko:',len(dictionary),'locally authored UI translations and SVG text')
